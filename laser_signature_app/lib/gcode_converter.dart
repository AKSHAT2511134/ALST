import 'package:flutter/material.dart';

class GcodeConverter {
  // Machine physical size in mm
  static const double machineWidth  = 100.0; // mm
  static const double machineHeight = 60.0;  // mm
  static const double feedRate      = 500.0; // mm/min (speed)
  static const int    laserPower    = 200;   // 0-255 (brightness)

  /// Main function: takes strokes from canvas, returns G-code string
  static String convert(List<List<Offset>> strokes, Size canvasSize) {
    final buffer = StringBuffer();

    // Header commands
    buffer.writeln('; Remote Laser Signature Machine');
    buffer.writeln('; Generated by Flutter App');
    buffer.writeln('G21');       // units = millimeters
    buffer.writeln('G28');       // home all axes (go to 0,0)
    buffer.writeln('M5');        // laser OFF at start
    buffer.writeln('G90');       // absolute coordinates mode

    // Process each stroke
    for (final stroke in strokes) {
      if (stroke.length < 2) continue;

      // First point of stroke: rapid move with laser OFF
      final startX = _toMachineX(stroke.first.dx, canvasSize.width);
      final startY = _toMachineY(stroke.first.dy, canvasSize.height);
      buffer.writeln('G0 X${startX.toStringAsFixed(2)} Y${startY.toStringAsFixed(2)}');

      // Turn laser ON
      buffer.writeln('M3 S$laserPower');

      // Remaining points: controlled move with laser ON
      for (int i = 1; i < stroke.length; i++) {
        final x = _toMachineX(stroke[i].dx, canvasSize.width);
        final y = _toMachineY(stroke[i].dy, canvasSize.height);
        buffer.writeln('G1 X${x.toStringAsFixed(2)} Y${y.toStringAsFixed(2)} F$feedRate');
      }

      // Turn laser OFF between strokes
      buffer.writeln('M5');
    }

    // Footer: return home
    buffer.writeln('G0 X0 Y0');
    buffer.writeln('M5');
    buffer.writeln('; DONE');

    return buffer.toString();
  }

  /// Convert canvas X pixel → machine X in mm
  static double _toMachineX(double px, double canvasW) {
    return (px / canvasW) * machineWidth;
  }

  /// Convert canvas Y pixel → machine Y in mm
  /// Note: Y axis is flipped (canvas Y goes down, machine Y goes up)
  static double _toMachineY(double py, double canvasH) {
    return machineHeight - (py / canvasH) * machineHeight;
  }
}